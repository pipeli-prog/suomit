const M = (q, right, wrong, say) => {
  const o = [...wrong];
  let h = 0;
  for (const ch of q) h = (h * 31 + ch.charCodeAt(0)) >>> 0;
  const a = h % (o.length + 1);
  o.splice(a, 0, right);
  return say ? { q, o, a, say } : { q, o, a };
};
